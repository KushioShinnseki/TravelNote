import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
import path from 'node:path'
import fs from 'node:fs'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.TRAVELNOTE_PLAYWRIGHT_PATH || 'playwright')
const browser=await chromium.launch({channel:'msedge',headless:true})
try {
 const page=await browser.newPage({viewport:{width:320,height:568}})
 const apiCalls=[],errors=[]
 page.on('request',request=>{if(new URL(request.url()).pathname.startsWith('/api/'))apiCalls.push(request.url())})
 page.on('pageerror',error=>errors.push(error.message))
 page.on('dialog',dialog=>dialog.accept())
 await page.goto(process.env.TRAVELNOTE_LOCAL_URL||'http://127.0.0.1:5175/')
 await page.locator('.plans-header').waitFor()
 await page.getByPlaceholder('例如：京都三日游').fill('京都三日游')
 await page.getByRole('button',{name:'创建计划',exact:true}).click()
 await page.locator('.trip-summary strong').filter({hasText:'京都三日游'}).waitFor()
 await page.locator('.local-bottom-nav button').nth(0).click()
 await page.locator('.page-heading .primary-button').click()
 await page.locator('.destination-modal input').nth(0).fill('清水寺')
 await page.locator('.destination-modal input').nth(1).fill('京都')
 await page.locator('.destination-modal input').nth(2).fill('东山')
 await page.locator('.destination-modal .modal-footer .primary-button').click()
 await page.locator('.destination-card h3').filter({hasText:'清水寺'}).waitFor()
 await page.locator('.local-bottom-nav button').nth(1).click()
 await page.locator('.plans-header .primary-button').click()
 await page.locator('.plan-place-choice input').check()
 await page.locator('.plan-modal textarea').nth(0).fill('寺院参观')
 await page.locator('.plan-modal textarea').nth(1).fill('# 行前准备\n带上相机')
 await page.locator('.plan-modal .modal-footer .primary-button').click()
 await page.locator('.plan-main h3').filter({hasText:'清水寺'}).waitFor()
 await page.reload()
 await page.locator('.plan-main h3').filter({hasText:'清水寺'}).waitFor()
 assert.equal(await page.locator('.plan-row time').textContent(),'全天')
 for(const [width,height] of [[320,568],[360,640],[390,844],[568,320],[768,1024],[1024,768]]) {
  await page.setViewportSize({width,height})
  await page.waitForTimeout(100)
  const dimensions=await page.evaluate(()=>({viewport:innerWidth,scroll:document.documentElement.scrollWidth}))
  assert.ok(dimensions.scroll<=width,`Page overflows at ${width}: ${JSON.stringify(dimensions)}`)
 }
 await page.setViewportSize({width:320,height:568})
 await page.locator('.plan-actions button').first().click()
 await page.locator('.plan-modal').waitFor()
 const modal=await page.locator('.plan-modal').boundingBox()
 assert.ok(modal.x>=0&&modal.x+modal.width<=320,'Modal exceeds 320px viewport')
 await page.locator('.plan-modal .modal-footer .primary-button').scrollIntoViewIfNeeded()
 assert.ok(await page.locator('.plan-modal .modal-footer .primary-button').isVisible())
 fs.mkdirSync(path.resolve('artifacts'),{recursive:true})
 await page.screenshot({path:path.resolve('artifacts/travelnote-local-320.png')})
 await page.locator('.plan-modal .close-button').click()
 await page.locator('.local-bottom-nav button').nth(2).click()
 assert.equal(await page.locator('.qr-stage').count(),0,'Local backup page must not show QR exchange')
 assert.equal(await page.locator('.export-scope').count(),0)
 const downloaded=page.waitForEvent('download')
 await page.locator('.exchange-card .primary-button').click()
 const backup=JSON.parse(fs.readFileSync(await (await downloaded).path(),'utf8'))
 assert.equal(backup.source,'travelnote-local')
 assert.equal(backup.plans.length,1)
 // Import a webpage JSON, then verify the updated place also updates its route.
 const fromWeb=structuredClone(backup);delete fromWeb.source;fromWeb.accountId='web-123';fromWeb.destinations[0].name='网页更新后的清水寺'
 await page.locator('#import-file').setInputFiles({name:'web.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(fromWeb))})
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('travelnote-local-workspace-v1')).destinations[0].name==='网页更新后的清水寺')
 const afterImport=await page.evaluate(()=>JSON.parse(localStorage.getItem('travelnote-local-workspace-v1')))
 assert.match(afterImport.plans[0].destination,/网页更新后的清水寺/)
 // The web importer maps a local packet to the current authenticated account.
 const webPage=await browser.newPage({viewport:{width:1024,height:768}})
 webPage.on('dialog',dialog=>dialog.accept())
 let workspace={format:'travelnote',version:3,profile:{home:''},destinations:[],plans:[],trips:[],tagCatalog:[]},writes=0,lastBody
 await webPage.route('**/api/auth/me',route=>route.fulfill({json:{account:{id:'web-1',username:'Tester'}}}))
 await webPage.route('**/api/workspace',async route=>{
  if(route.request().method()==='PUT'){lastBody=route.request().postDataJSON();workspace=lastBody;writes++}
  await route.fulfill({json:workspace})
 })
 await webPage.goto(process.env.TRAVELNOTE_WEB_URL||'http://127.0.0.1:5176/')
 await webPage.locator('.main-nav button').nth(2).click()
 await webPage.locator('#import-file').setInputFiles({name:'local.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))})
 await webPage.waitForFunction(()=>document.querySelector('.toast')?.textContent.includes('数据包已导入'))
 assert.equal(writes,1);assert.equal(lastBody.accountId,'web-1');assert.equal(lastBody.plans.length,1)
 await webPage.locator('#import-file').setInputFiles({name:'foreign.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...fromWeb,accountId:'other-web-account'}))})
 await webPage.waitForFunction(()=>document.querySelector('.toast')?.textContent.includes('账号不匹配'))
 assert.equal(writes,1,'Another web account must not bypass account validation')
 await webPage.close()
 const corrupt=await browser.newPage()
 await corrupt.addInitScript(()=>localStorage.setItem('travelnote-local-workspace-v1','{"bad":true}'))
 await corrupt.goto(process.env.TRAVELNOTE_LOCAL_URL||'http://127.0.0.1:5175/')
 await corrupt.locator('.auth-card p').filter({hasText:'原文件已保留'}).waitFor()
 assert.equal(await corrupt.evaluate(()=>localStorage.getItem('travelnote-local-workspace-v1')),'{"bad":true}')
 await corrupt.close()
 assert.equal(apiCalls.length,0,'Local planner called a server API')
 assert.deepEqual(errors,[])
 console.log('PASS: offline planning, persistence, 320–1024px layout, backups, web/local JSON exchange, web account checks, corrupt-data recovery, zero local API calls')
} finally {await browser.close()}
